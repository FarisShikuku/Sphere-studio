package com.example.sphere.model

import androidx.compose.ui.graphics.Color

enum class MaterialSurfaceMode(val label: String, val description: String) {
    SURFACE_ONLY("Surface Texture", "Flat 2D PBR plane with normal & height mapping. Zero geometry cost."),
    GEOMETRY_3D("3D Geometry", "Procedural volumetric or instanced geometry (blades, shells, voxels).")
}

enum class MaterialChannelMode(val label: String, val shortDesc: String) {
    COMPOSITE_PBR("Full PBR", "Complete Cook-Torrance BRDF with dynamic lighting"),
    ALBEDO_MAP("Albedo", "sRGB diffuse reflectance (BC7)"),
    NORMAL_MAP("Normal Map", "Tangent-space surface normals (BC5)"),
    ORM_MAP("ORM Map", "Red=AO, Green=Roughness, Blue=Metallic (BC7)"),
    HEIGHT_MAP("Height Map", "Displacement & parallax depth (BC4)"),
    REFRACT_SSS_MAP("Optics / SSS", "Refraction transmission & subsurface scatter"),
    SPLIT_COMPARE("Split Compare", "Interactive split comparing Surface vs 3D Geometry")
}

data class PbrMaterial(
    val id: String,
    val name: String,
    val category: String,
    val description: String,
    val baseColor: Color,
    val roughness: Float,
    val metallic: Float,
    val occlusion: Float = 1.0f,
    // Optical & Refraction (Sascha Willems PBR / Raytracing)
    val transmission: Float = 0.0f, // 0 = opaque, 1 = transmissive
    val ior: Float = 1.50f,        // Index of Refraction (1.0 to 2.5)
    val dispersion: Float = 0.0f,  // Chromatic aberration (Abbe number)
    val refractionRoughness: Float = 0.0f, // Frosted refraction blur
    val absorptionColor: Color = Color.White,
    // Subsurface Scattering (SSS)
    val subsurface: Float = 0.0f,
    val subsurfaceColor: Color = Color(0.85f, 0.92f, 0.45f),
    val subsurfaceRadiusMm: Float = 1.0f,
    // Perturbation & Tiling
    val normalScale: Float = 1.0f,
    val displacementDepthMeters: Float = 0.02f,
    val surfaceMode: MaterialSurfaceMode = MaterialSurfaceMode.SURFACE_ONLY,
    val tileScaleMeters: Float = 1.0f,
    val assetPath: String? = null,
    // Specific Procedural Generator Parameters
    val mortarWidthMm: Float = 10.0f,
    val mortarDepthMm: Float = 6.0f,
    val brickRustication: Float = 0.75f,
    val efflorescence: Float = 0.15f,
    val bladeDensity: Float = 2400f, // blades/m^2
    val bladeLengthMm: Float = 45f,
    val windSway: Float = 0.6f,
    val thatchRatio: Float = 0.2f,
    val foliageCoveragePct: Float = 40f, // 0 - 100%
    val soilMoisture: Float = 0.35f,
    val pebbleCount: Float = 120f,
    // Vulkan Texture & Memory Specification
    val resolution: Int = 2048,
    val albedoFormat: String = "BC7_UNORM_SRGB",
    val normalFormat: String = "BC5_UNORM",
    val ormFormat: String = "BC7_UNORM",
    val heightFormat: String = "BC4_UNORM",
    val bindlessAlbedoSlot: Int = 101,
    val bindlessNormalSlot: Int = 102,
    val bindlessOrmSlot: Int = 103,
    val bindlessHeightSlot: Int = 104
)

