    val fifthWheelOffsetM: Float,
    val cabHeightM: Float,
    val engineTorqueNm: Float,
    val enginePowerHp: Float,
    val passengerCapacity: Int,
    val lengthM: Float,
    val widthM: Float,
    val heightM: Float,
    val groundClearanceM: Float,
    val tireSpecLabel: String,
    val actionLabel: String,
    val defaultLivery: VehicleLiveryPreset,
    val livery: VehicleLiveryPreset = defaultLivery,
